#!/usr/bin/env python3
"""Produce a factual, machine-generated Android-port readiness report for the pinned upstream tree.

This is a source inventory, not a proof of runtime compatibility and not a game build.
It deliberately exits nonzero only when the pinned upstream checkout is missing.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

REQUIRED = (
    "CMakeLists.txt",
    "Port/CMakeLists.txt",
    "Port/src/main.cpp",
    "Tools/generate.py",
    "Tools/sotc_link.py",
    "Docs/ARCHITECTURE.md",
    "Docs/GAME_BUILD.md",
    "Port/recomp/sotc.toml",
)

PATTERNS = (
    ("Windows APIs", re.compile(r"#\s*include\s*[<\"]windows\.h[>\"]|GetModuleFileNameW|SetPriorityClass|_putenv_s|CaptureStackBackTrace")),
    ("MSVC-specific build flags", re.compile(r"/arch:AVX2|/bigobj|/d2OptimizeHugeFunctions|MSVC")),
    ("Windows-only generation assumptions", re.compile(r"ps2_recomp\.exe|vu1_recomp\.exe|build\.bat")),
    ("OpenGL fragment-interlock requirement", re.compile(r"GL_ARB_fragment_shader_interlock|GL_INTEL_fragment_shader_ordering|GL_EXT_fragment_shader_interlock")),
    ("x86 SIMD intrinsics", re.compile(r"#\s*include\s*[<\"](?:immintrin|xmmintrin|emmintrin)\.h[>\"]|_mm256_|_mm_storeu_ps|_mm_loadu_ps")),
)

SOURCE_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".cmake", ".txt", ".toml", ".py"}


def git_value(repo: Path, *args: str) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(repo), *args], text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--upstream", default="upstream/sotc-vibe-pc")
    parser.add_argument("--output", default="build/ANDROID_PORT_AUDIT.md")
    args = parser.parse_args()

    upstream = Path(args.upstream).resolve()
    missing = [name for name in REQUIRED if not (upstream / name).is_file()]
    if not upstream.is_dir() or missing:
        details = ", ".join(missing) if missing else "directory not found"
        raise SystemExit(f"Upstream checkout missing required files: {details}")

    scanned = 0
    hits: dict[str, list[str]] = {label: [] for label, _ in PATTERNS}
    for path in upstream.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in SOURCE_SUFFIXES:
            continue
        if any(part in {".git", "build", "generated"} for part in path.parts):
            continue
        try:
            data = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        scanned += 1
        relative = path.relative_to(upstream).as_posix()
        for label, pattern in PATTERNS:
            if pattern.search(data):
                hits[label].append(relative)

    generated = upstream / "Port/generated/register_functions.cpp"
    generation_present = generated.is_file()
    pinned = git_value(upstream, "rev-parse", "HEAD")
    tag = git_value(upstream, "describe", "--tags", "--exact-match")

    lines = [
        "# Android port readiness audit",
        "",
        "> Generated by `scripts/android_port_audit.py`. This is a static source audit only; it does not compile or run the game.",
        "",
        "## Upstream source",
        "",
        f"- Checkout: `{upstream.name}`",
        f"- Pinned commit: `{pinned}`",
        f"- Exact tag: `{tag}`",
        f"- Text/source files scanned: {scanned}",
        f"- Generated game C++ present: {'yes' if generation_present else 'no'}",
        "",
        "## Porting blockers detected",
        "",
    ]

    descriptions = {
        "Windows APIs": "The host layer contains Windows-specific API calls that need Android/POSIX alternatives or compile-time guards.",
        "MSVC-specific build flags": "Build settings need compiler/platform-specific CMake branches; MSVC options cannot be passed to Clang/NDK.",
        "Windows-only generation assumptions": "The code-generation helper assumes Windows executable names or batch files; host-tool generation needs a Linux-compatible path for CI.",
        "OpenGL fragment-interlock requirement": "The GS renderer has fragment-ordering/interlock paths that must be audited against Android Vulkan/GLES capability and correctness.",
        "x86 SIMD intrinsics": "x86 SIMD code needs equivalent AArch64 NEON or portable code paths before ARM64 can compile.",
    }
    for label, _ in PATTERNS:
        paths = sorted(set(hits[label]))
        lines.append(f"### {label}")
        lines.append("")
        lines.append(descriptions[label])
        lines.append("")
        if paths:
            for item in paths[:20]:
                lines.append(f"- `{item}`")
            if len(paths) > 20:
                lines.append(f"- … and {len(paths) - 20} more matching files")
        else:
            lines.append("- No matches in the scanned checkout.")
        lines.append("")

    lines += [
        "## Build-generation limitation",
        "",
        "The upstream repository intentionally does not track `Port/generated/`. Those sources are generated from the supported user-supplied game image, so this CI must not claim to build the game engine merely because the Android shell APK succeeds.",
        "",
        "## Current milestone",
        "",
        "- Android launcher/APK shell can be built separately from the game runtime.",
        "- This report inventories source-level blockers to guide the port; it is not proof that the native engine works on Android.",
        "- The actual-game milestone requires ARM64 compilation of the generated EE/VU code, an Android platform/input/audio layer, and a correct Android-capable GS renderer, followed by real gameplay tests on device.",
        "",
    ]

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {output}")
    print(f"Upstream {pinned}; scanned {scanned} files; generated game sources present={generation_present}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
